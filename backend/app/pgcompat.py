"""Run FlowPilot's own storage on Postgres.

FlowPilot's SQL is written for SQLite. This module gives Postgres the same small interface the code already uses
(`with conn() as db: db.execute(sql, params).fetchone()["name"]`), translating the few places where the two
databases differ. Set FLOWPILOT_DATABASE_URL=postgresql://user:password@host:5432/dbname to use it.
"""
from __future__ import annotations

import re
from typing import Any

import psycopg

_connect = psycopg.connect  # kept apart so code that swaps psycopg.connect (the Database Query node tests) cannot affect FlowPilot storage

# Tables whose autogenerated id the code reads back after an insert (cursor.lastrowid in SQLite).
RETURNS_ID = {"audit_log", "data_rows", "workflow_versions"}


class Row(dict):
    """A result row readable by column name or by position, like sqlite3.Row."""

    def __getitem__(self, key):
        if isinstance(key, int): return list(self.values())[key]
        return super().__getitem__(key)


def _row_factory(cursor):
    names = [c.name for c in cursor.description or []]
    return lambda values: Row(zip(names, values))


def translate(sql: str) -> str:
    """SQLite dialect to Postgres: `?` placeholders, literal `%`, AUTOINCREMENT, REAL, INSERT OR IGNORE."""
    out, quote = [], False
    for ch in sql:
        if ch == "'": quote = not quote
        if ch == "?" and not quote: out.append("%s")
        elif ch == "%": out.append("%%")
        else: out.append(ch)
    text = "".join(out)
    text = re.sub(r"INTEGER PRIMARY KEY AUTOINCREMENT", "BIGSERIAL PRIMARY KEY", text, flags=re.I)
    text = re.sub(r"\bREAL\b", "DOUBLE PRECISION", text)
    if re.match(r"\s*INSERT\s+OR\s+IGNORE\s+INTO", text, re.I):
        text = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", text, count=1, flags=re.I).rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return text


def _params(params) -> tuple:
    return tuple(int(p) if isinstance(p, bool) else p for p in (params or ()))


class _Cursor:
    def __init__(self, cur, rows=None, lastrowid=None, connection=None):
        self._cur, self._rows, self.lastrowid, self.connection = cur, rows, lastrowid, connection

    @property
    def rowcount(self) -> int: return self._cur.rowcount if self._cur is not None else len(self._rows or [])

    def fetchone(self):
        if self._rows is not None: return self._rows[0] if self._rows else None
        return self._cur.fetchone() if self._cur.description else None

    def fetchall(self):
        if self._rows is not None: return list(self._rows)
        return self._cur.fetchall() if self._cur.description else []

    def __iter__(self): return iter(self.fetchall())


class PgConnection:
    """What `conn()` returns in Postgres mode. Commits when the `with` block ends normally, rolls back on error, and always closes."""

    def __init__(self, url: str):
        self._db = _connect(url, row_factory=_row_factory)  # type: ignore[arg-type]

    def __enter__(self): return self

    def __exit__(self, exc_type, *_):
        try:
            if exc_type is None: self._db.commit()
            else: self._db.rollback()
        finally: self._db.close()
        return False

    def close(self) -> None: self._db.close()

    def commit(self) -> None: self._db.commit()

    def execute(self, sql: str, params=()) -> _Cursor:
        head = sql.lstrip()
        upper = head[:40].upper()
        if upper.startswith("PRAGMA"):
            m = re.match(r"PRAGMA\s+table_info\((\w+)\)", head, re.I)
            if not m: return _Cursor(None, [], connection=self)
            cur = self._db.execute("SELECT column_name AS name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = %s", (m.group(1),))
            return _Cursor(None, cur.fetchall(), connection=self)
        text = translate(sql)
        table = re.match(r"\s*INSERT\s+INTO\s+(\w+)", text, re.I)
        if table and table.group(1).lower() in RETURNS_ID and "RETURNING" not in text.upper():
            cur = self._db.execute(text + " RETURNING id", _params(params))
            return _Cursor(None, [], cur.fetchone()["id"], self)
        return _Cursor(self._db.execute(text, _params(params)), connection=self)

    def executemany(self, sql: str, seq) -> _Cursor:
        cur = self._db.cursor()
        cur.executemany(translate(sql), [_params(p) for p in seq])
        return _Cursor(cur, connection=self)
